#!/usr/bin/env node
/**
 * Inline the approved golden mascot artwork into a generated module.
 *
 * The Companion runs as an MV3 content script: it cannot read the filesystem
 * and `chrome.runtime.getURL` would require `web_accessible_resources`, which
 * would make the image reachable by the provider page.  Inlining the bytes
 * keeps the content script self-contained, keeps the approved PNGs read-only,
 * and lets the Node test fixtures exercise the same code path.
 *
 * Only the artwork the motion layer actually shows is embedded.  Trust states
 * deliberately reuse the idle figure: the brief asks the *motion* (glow,
 * scale, shake) to carry the verdict, not a different picture.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "golden/production-mascot/ui");
const outPath = join(root, "packages/companion/mascot-assets.generated.js");

/** motion state → golden artwork file */
export const COMPANION_MASCOT_SOURCES = Object.freeze({
  idle: "safi-ui-idle.png",
  translating: "safi-ui-translating.png",
});

const entries = [];
for (const [state, file] of Object.entries(COMPANION_MASCOT_SOURCES)) {
  const bytes = await readFile(join(source, file));
  entries.push(`  ${state}: "data:image/png;base64,${bytes.toString("base64")}",`);
}

const file = `/**
 * GENERATED by tools/gen-companion-mascot-assets.mjs — do not edit by hand.
 * Run \`npm run mascot:companion\` after changing the golden artwork.
 *
 * Data URIs, not URLs: the content script must not need a network fetch or a
 * web-accessible resource to draw Safi.
 */
export const SAFI_COMPANION_MASCOT_SOURCES = Object.freeze(${JSON.stringify(COMPANION_MASCOT_SOURCES)});

export const SAFI_COMPANION_MASCOT_ASSETS = Object.freeze({
${entries.join("\n")}
});
`;

await writeFile(outPath, file, "utf8");
const kb = Math.round((await readFile(outPath)).byteLength / 1024);
console.log(`Built packages/companion/mascot-assets.generated.js (${kb} KB, ${Object.keys(COMPANION_MASCOT_SOURCES).length} figures)`);
