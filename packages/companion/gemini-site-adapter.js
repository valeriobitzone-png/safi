/**
 * GeminiSiteAdapter — DOM-only Companion adapter for the Gemini web app.
 *
 * Phase 8A.  This module is the *only* place that knows anything about the
 * Gemini DOM.  It implements exactly the same contract as every other
 * CompanionSiteAdapter, so the shared vertical slice, permission ledger,
 * observer lifecycle, mutation guard, projection contract and Manual
 * fallback are reused verbatim: there is no Gemini branch anywhere else.
 *
 * Every selector below was measured on the live, authenticated page and is
 * documented in artifacts/companion-live/gemini/dom-discovery.md.  The
 * Gemini UI is localized, so no localized `aria-label` is ever a primary
 * selector; labels appear only inside a bounded secondary allowlist.  Class
 * names are generated by the build and are never used.
 *
 * Invariants preserved here: no global scan, no OCR, no other tab or app,
 * no send control is ever clicked, no partial streaming text is exposed, and
 * an unrecognized document fails closed.
 */

const GEMINI_HOSTS = new Set(["gemini.google.com"]);
const PROJECTION_TRUST_STATUSES = new Set(["VERIFIED", "UNCERTAIN", "FAILED"]);

/**
 * Bounded selector allowlist.  Each entry is a specific, known node of the
 * Gemini document; the adapter never walks the DOM looking for "something
 * that looks like" a response.
 */
const SELECTORS = Object.freeze({
  conversation: Object.freeze([
    '[data-test-id="chat-history-container"]',
    "infinite-scroller",
  ]),
  composerContainer: Object.freeze([
    "rich-textarea",
  ]),
  composer: Object.freeze([
    'rich-textarea [contenteditable="true"][role="textbox"]',
    '[contenteditable="true"][role="textbox"][aria-multiline="true"]',
    '[contenteditable="true"][role="textbox"]',
  ]),
  modelTurn: Object.freeze([
    "model-response",
    '[data-test-id="model-response"]',
  ]),
  userTurn: Object.freeze(["user-query"]),
  responseContainer: Object.freeze(["response-container"]),
  content: Object.freeze([
    "model-response-content",
    "message-content",
    '[data-test-id="model-response-content"]',
  ]),
});

/**
 * Structural fallbacks inside the recognized response container.  These are
 * only consulted when no explicit content element is found, and each one
 * names the nodes that must be excluded: the model label, the thinking UI and
 * the action toolbar.  Falling back to the whole container is deliberately
 * *not* an option, because that container also holds the "Gemini ha detto"
 * label and would certify text the user never reads as the answer.
 */
const STRUCTURE_EXCLUDE = Object.freeze([
  "message-actions",
  "[aria-live]",
  "thinking-overlay",
  "sensitive-memories-banner",
  "user-query",
]);

/**
 * Bounded allowlist of real streaming signals.
 *
 * Two localization-independent signals carry the observation:
 *  - `aria-busy="true"` on the response's own live region, next to the text;
 *  - the stop icon rendered inside the composer's send container, which on
 *    the live site lives in the composer and therefore *outside* the response
 *    subtree.  This is the same structural trap that once broke the ChatGPT
 *    observer, so the composer root is queried explicitly.
 *
 * The localized `aria-label`s are a bounded secondary allowlist only.
 */
const STREAMING_SIGNALS = Object.freeze({
  attributes: Object.freeze(["aria-busy", "data-state", "data-status", "aria-busy-state"]),
  // The live region that carries `aria-busy` is a *descendant* of the response
  // container, so the attribute is probed through a bounded selector list
  // rather than only on the roots themselves.
  attributeSelectors: Object.freeze([
    '[aria-live][aria-busy]',
    '[aria-busy]',
    "[data-state]",
    "[data-status]",
  ]),
  busyValues: Object.freeze(["true", "streaming", "busy", "in-progress", "generating", "pending"]),
  busyPattern: /(?:stream|generat|in-?progress|partial|pending|busy)/,
  settledPattern: /(?:not|complete|completed|done|idle|finished|error|failed|aborted|false)/,
  controls: Object.freeze([
    '[data-test-id="send-button-container"] mat-icon[data-mat-icon-name="stop"]',
    '[data-test-id="send-button-container"] [data-mat-icon-name="stop"]',
    'mat-icon[data-mat-icon-name="stop"]',
    "stop-button",
    'button[aria-label="Stop"]',
    'button[aria-label="Stop response"]',
    'button[aria-label="Stop generating"]',
    'button[aria-label="Interrompi"]',
    'button[aria-label="Interrompi risposta"]',
    'button[aria-label*="Interrompi"]',
    'button[aria-label*="Stop"]',
    'button[aria-label*="Annulla"]',
    'button[aria-label*="Ferma"]',
  ]),
});

/**
 * Controls the Companion panel may never cover, specific to this provider.
 *
 * Only *controls* belong here.  The conversation surface is deliberately
 * excluded: on Gemini it spans the whole centre of the window, so treating it
 * as critical makes every anchor collide and forces the panel on top of the
 * send control.  Measured live: with the surface included the resolver still
 * reported a collision on the send button.
 */
export const GEMINI_PANEL_CRITICAL_SELECTORS = Object.freeze([
  '[data-test-id="send-button-container"]',
  "rich-textarea",
]);

const DEFAULT_STABLE_WINDOWS = 2;
const ANCESTOR_DEPTH = 6;
const STRUCTURE_DEPTH = 3;

function attr(node, name) {
  try {
    return node?.getAttribute?.(name) ?? null;
  } catch {
    return null;
  }
}

function hasAttr(node, name) {
  try {
    return node?.hasAttribute?.(name) === true;
  } catch {
    return false;
  }
}

function lower(value) {
  return String(value ?? "").toLowerCase();
}

function tagOf(node) {
  return String(node?.tagName ?? "").toLowerCase();
}

/**
 * A node counts as visible only when it is rendered *and* occupies space.
 * Gemini keeps a zero-area offscreen clipboard mirror in the DOM, so the
 * area check is part of recognition, not an optimisation.
 */
function isVisible(node) {
  if (!node) return false;
  try {
    if (node.hidden === true) return false;
    if (lower(attr(node, "aria-hidden")) === "true") return false;
    if (lower(attr(node, "aria-disabled")) === "true") return false;
    if (lower(attr(node, "data-safi-ignore")) === "true") return false;
    const rect = node.getBoundingClientRect?.();
    if (rect && (rect.width <= 0 || rect.height <= 0)) return false;
    const view = node.ownerDocument?.defaultView;
    if (view?.getComputedStyle) {
      const style = view.getComputedStyle(node);
      if (style?.display === "none" || style?.visibility === "hidden") return false;
    }
    return true;
  } catch {
    return false;
  }
}

function matchesSelector(node, selector) {
  try {
    if (typeof node.matches === "function") return node.matches(selector);
  } catch {
    // A minimal DOM fixture may not implement matches.
  }
  return false;
}

function unique(nodes) {
  return [...new Set(nodes.filter(Boolean))];
}

function queryAll(root, selector) {
  try {
    if (!root?.querySelectorAll) return [];
    return [...root.querySelectorAll(selector)];
  } catch {
    return [];
  }
}

function queryWithin(root, selectors) {
  const result = [];
  for (const selector of selectors) {
    if (root && matchesSelector(root, selector)) result.push(root);
    result.push(...queryAll(root, selector));
  }
  return unique(result).filter(isVisible);
}

function textOf(node) {
  if (!node) return null;
  try {
    const tag = tagOf(node);
    if ((tag === "textarea" || tag === "input") && typeof node.value === "string") return node.value;
    if (typeof node.textContent === "string") return node.textContent;
    if (typeof node.value === "string") return node.value;
    return null;
  } catch {
    return null;
  }
}

function elementKey(node) {
  if (!node) return null;
  return attr(node, "data-test-id") ?? attr(node, "data-testid") ?? attr(node, "id") ?? null;
}

function unavailable(reason, details = {}) {
  return Object.freeze({
    ok: false,
    status: "COMPANION_UNAVAILABLE",
    reason: String(reason),
    ...details,
  });
}

function permissionRequired(permission) {
  return Object.freeze({
    ok: false,
    status: "PERMISSION_REQUIRED",
    permission,
    reason: `${permission} requires explicit authorization and a user gesture`,
  });
}

function authorized(options, permission) {
  if (options?.authorized !== true || options?.userGesture !== true) {
    return permissionRequired(permission);
  }
  return null;
}

/**
 * Composer scoring.  `role="textbox"` + `aria-label` + `contenteditable`
 * identifies the real editor; the offscreen Quill clipboard mirror scores
 * only on `contenteditable` and is additionally rejected by `isVisible`.
 */
function composerScore(node) {
  try {
    let score = 0;
    if (tagOf(node) === "rich-textarea") score += 6;
    if (lower(attr(node, "role")) === "textbox") score += 5;
    if (lower(attr(node, "contenteditable")) === "true") score += 3;
    if (hasAttr(node, "aria-label")) score += 2;
    if (hasAttr(node, "aria-multiline")) score += 1;
    if (hasAttr(node, "data-placeholder")) score += 1;
    if (node.closest?.("rich-textarea")) score += 4;
    return score;
  } catch {
    return 0;
  }
}

/**
 * Content candidates are scored by specificity, not equally.
 *
 * Measured live: inside one response container Gemini renders *both*
 * `model-response-content` and a `message-content` element that wrap the very
 * same text.  With equal scores the deliberate "ambiguous is unsafe" rule
 * returned nothing and the adapter could not certify a perfectly good answer.
 * The dedicated element wins; a genuine tie between two different texts still
 * fails closed.
 */
function contentScore(node) {
  try {
    let score = 0;
    if (tagOf(node) === "model-response-content") score += 8;
    if (lower(attr(node, "data-test-id")) === "model-response-content") score += 9;
    if (tagOf(node) === "message-content") score += 6;
    if (tagOf(node) === "div" || tagOf(node) === "section") score += 1;
    return score;
  } catch {
    return 0;
  }
}

function modelScore(node) {
  try {
    let score = 0;
    if (tagOf(node) === "model-response") score += 9;
    if (lower(attr(node, "data-test-id")) === "model-response") score += 9;
    if (tagOf(node) === "model-response-content") score += 6;
    return score;
  } catch {
    return 0;
  }
}

/**
 * A unique best match or nothing.  An ambiguous composer is unsafe, so a tie
 * fails closed; the newest model turn is resolved separately by document
 * order because a conversation naturally holds several.
 */
function bestUnique(nodes, score) {
  const visible = unique(nodes).filter(isVisible).map((node) => ({ node, score: score(node) }));
  visible.sort((left, right) => right.score - left.score);
  if (visible.length === 0 || visible[0].score <= 0) return null;
  if (visible.filter((entry) => entry.score === visible[0].score).length > 1) return null;
  return visible[0].node;
}

function latestModelTurn(nodes) {
  const candidates = unique(nodes)
    .filter(isVisible)
    .map((node) => ({ node, score: modelScore(node) }))
    .filter((entry) => entry.score > 0);
  if (candidates.length === 0) return null;
  const highest = Math.max(...candidates.map((entry) => entry.score));
  const top = candidates.filter((entry) => entry.score === highest);
  return top[top.length - 1].node;
}

function boundedRoots(node, extra = []) {
  const roots = [];
  let current = node;
  let depth = 0;
  while (current && depth < ANCESTOR_DEPTH) {
    roots.push(current);
    current = current.parentNode;
    depth += 1;
  }
  for (const root of extra) {
    if (root) roots.push(root);
  }
  return unique(roots);
}

/**
 * Inspect only the bounded streaming allowlist.  Returns the name of the
 * signal that fired, or null.  A null result is never proof of completion:
 * stability is proven separately by the consecutive-equal-snapshot window.
 */
function streamingSignal(roots) {
  for (const root of roots) {
    for (const name of STREAMING_SIGNALS.attributes) {
      const value = lower(attr(root, name));
      if (!value || STREAMING_SIGNALS.settledPattern.test(value)) continue;
      if (STREAMING_SIGNALS.busyValues.includes(value)) return `attribute:${name}`;
      if (STREAMING_SIGNALS.busyPattern.test(value)) return `attribute:${name}`;
    }
    for (const selector of STREAMING_SIGNALS.attributeSelectors) {
      for (const node of queryAll(root, selector)) {
        for (const name of STREAMING_SIGNALS.attributes) {
          const value = lower(attr(node, name));
          if (!value || STREAMING_SIGNALS.settledPattern.test(value)) continue;
          if (STREAMING_SIGNALS.busyValues.includes(value)) return `attribute:${name}`;
          if (STREAMING_SIGNALS.busyPattern.test(value)) return `attribute:${name}`;
        }
      }
    }
    for (const selector of STREAMING_SIGNALS.controls) {
      if (queryAll(root, selector).length > 0) return `control:${selector}`;
    }
  }
  return null;
}

/**
 * Bounded structural fallback for the answer text.
 *
 * A child is only accepted when it carries text **and** contains none of the
 * excluded UI nodes.  A child that *does* contain an excluded node is not
 * accepted and not discarded: it is descended into.  This matters because
 * Gemini sometimes renders the answer without the `model-response-content`
 * element, inside a wrapper that also holds the "Gemini ha detto" live
 * region.  Accepting that wrapper would certify the model label together with
 * the answer, which is not the text the reader sees as the response.
 */
function structuralContent(container) {
  let level = [container];
  for (let depth = 0; depth <= STRUCTURE_DEPTH; depth += 1) {
    const next = [];
    for (const parent of level) {
      for (const child of [...(parent.children ?? [])]) {
        if (STRUCTURE_EXCLUDE.some((selector) => matchesSelector(child, selector))) continue;
        if (!isVisible(child)) continue;
        const carriesExcluded = queryAll(child, STRUCTURE_EXCLUDE.join(",")).length > 0;
        const text = textOf(child);
        if (!carriesExcluded && typeof text === "string" && text.trim().length > 0) return child;
        if (carriesExcluded) next.push(child);
      }
    }
    if (next.length === 0) break;
    level = next;
  }
  return null;
}

export class GeminiSiteAdapter {
  /**
   * @param {object} options
   * @param {Document} [options.document] current page document only
   * @param {Window} [options.window] current page window only
   * @param {Location|{hostname:string}} [options.location] current location only
   */
  constructor({ document: doc, window: win, location } = {}) {
    this.id = "gemini-site-adapter";
    this.provider = "gemini";
    this.document = doc ?? globalThis.document ?? null;
    this.window = win ?? this.document?.defaultView ?? globalThis.window ?? null;
    this.location = location ?? this.window?.location ?? this.document?.location ?? null;
    this._nodeKeys = new WeakMap();
    this._nextNodeKey = 1;
    this._stability = { key: null, text: null, since: 0, windows: 0 };
  }

  /** Controls the host panel must keep clear, parameterized by this adapter. */
  get criticalSelectors() {
    return GEMINI_PANEL_CRITICAL_SELECTORS;
  }

  _streamRoots(resolution) {
    return boundedRoots(resolution.content ?? resolution.assistant, [
      resolution.container,
      resolution.assistant,
      resolution.conversation,
      resolution.composerContainer,
    ]);
  }

  _noteStability({ key, text, streaming, now, requiredStableMs, requiredWindows }) {
    if (streaming) {
      this._stability = { key, text: null, since: now(), windows: 0 };
      return { stable: false, windows: 0 };
    }
    if (this._stability.key !== key || this._stability.text !== text) {
      this._stability = { key, text, since: now(), windows: 1 };
      return { stable: requiredStableMs <= 0 && requiredWindows <= 1, windows: 1 };
    }
    this._stability.windows += 1;
    const elapsed = now() - this._stability.since;
    return {
      stable: this._stability.windows >= requiredWindows && elapsed >= requiredStableMs,
      windows: this._stability.windows,
    };
  }

  /** Drop the stability window; used when a new turn boundary is observed. */
  resetStability() {
    this._stability = { key: null, text: null, since: 0, windows: 0 };
  }

  _responseKey(node) {
    if (!node || (typeof node !== "object" && typeof node !== "function")) return null;
    let key = this._nodeKeys.get(node);
    if (!key) {
      key = this._nextNodeKey++;
      this._nodeKeys.set(node, key);
    }
    return `dom:node-${key}`;
  }

  hostname() {
    const candidates = [];
    for (const source of [this.location, this.document?.location, this.window?.location]) {
      try {
        const hostname = source?.hostname ?? (source?.href ? new URL(source.href).hostname : "");
        if (hostname) candidates.push(lower(hostname));
      } catch {
        // A malformed or inaccessible location is not a supported origin.
      }
    }
    const uniqueHosts = [...new Set(candidates)];
    return uniqueHosts.length === 1 ? uniqueHosts[0] : "";
  }

  _resolve() {
    const conversation = bestUnique(
      queryWithin(this.document, SELECTORS.conversation),
      (node) => (matchesSelector(node, '[data-test-id="chat-history-container"]') ? 9 : 2),
    );
    const composerContainer = bestUnique(
      queryWithin(this.document, SELECTORS.composerContainer),
      () => 4,
    );
    const composerSearchRoot = composerContainer ?? this.document;
    const composer = bestUnique(queryWithin(composerSearchRoot, SELECTORS.composer), composerScore);
    const assistantRoot = conversation ?? this.document;
    const assistant = latestModelTurn(queryWithin(assistantRoot, SELECTORS.modelTurn));
    const container = assistant
      ? (queryWithin(assistant, SELECTORS.responseContainer)[0] ?? assistant)
      : null;
    let content = null;
    if (assistant) {
      const explicit = queryWithin(container ?? assistant, SELECTORS.content);
      content = bestUnique(explicit, contentScore) ?? structuralContent(container);
    }
    return { conversation, composerContainer, composer, assistant, container, content };
  }

  detect() {
    const host = this.hostname();
    const signals = [];
    if (GEMINI_HOSTS.has(host)) signals.push("gemini-host");
    if (!GEMINI_HOSTS.has(host)) {
      return Object.freeze({
        supported: false,
        status: "COMPANION_UNAVAILABLE",
        provider: this.provider,
        confidence: 0,
        signals,
        reason: "The current host is not a supported Gemini web origin",
      });
    }
    const resolution = this._resolve();
    if (resolution.conversation) signals.push("semantic-conversation");
    if (resolution.composerContainer) signals.push("semantic-composer-container");
    if (resolution.composer) signals.push("semantic-composer");
    if (resolution.assistant) signals.push("model-turn");
    if (resolution.content) signals.push("model-response");
    if (queryAll(this.document, '[data-test-id="send-button-container"]').length > 0) {
      signals.push("send-control");
    }
    if (!resolution.composerContainer || !resolution.composer) {
      return Object.freeze({
        supported: false,
        status: "COMPANION_UNAVAILABLE",
        provider: this.provider,
        confidence: resolution.conversation ? 0.5 : 0.25,
        signals,
        reason: "Gemini semantic composer signals were not found",
      });
    }
    let confidence = 0.5 + (resolution.conversation ? 0.2 : 0) + (resolution.assistant ? 0.15 : 0) + (resolution.content ? 0.15 : 0);
    if (streamSignalsPresent(this.document)) confidence = Math.min(1, confidence + 0.05);
    return Object.freeze({
      supported: true,
      status: "READY",
      provider: this.provider,
      confidence: Number(confidence.toFixed(2)),
      signals,
      reason: null,
    });
  }

  healthCheck() {
    const detection = this.detect();
    if (!detection.supported) return Object.freeze({ ...detection, ok: false });
    const resolution = this._resolve();
    if (!resolution.composerContainer || !resolution.composer) {
      return Object.freeze({
        ok: false,
        status: "COMPANION_UNAVAILABLE",
        provider: this.provider,
        confidence: detection.confidence,
        signals: detection.signals,
        reason: "Gemini DOM health check failed",
      });
    }
    return Object.freeze({
      ok: true,
      status: "READY",
      provider: this.provider,
      confidence: detection.confidence,
      signals: detection.signals,
      responseAvailable: Boolean(resolution.assistant && resolution.content),
      scopes: Object.freeze({
        conversation: elementKey(resolution.conversation),
        composer: elementKey(resolution.composer),
        composerContainer: elementKey(resolution.composerContainer),
        modelTurn: elementKey(resolution.assistant),
        response: elementKey(resolution.content),
      }),
    });
  }

  captureComposer(options = {}) {
    const denied = authorized(options, "composer:read");
    if (denied) return denied;
    const health = this.healthCheck();
    if (!health.ok) return health;
    const { composer } = this._resolve();
    if (!composer) return unavailable("Recognized composer disappeared before capture");
    const text = textOf(composer);
    if (typeof text !== "string" || text.length === 0) {
      return Object.freeze({ ok: false, status: "EMPTY_COMPOSER", reason: "The authorized composer is empty" });
    }
    return Object.freeze({
      ok: true,
      status: "CAPTURED",
      provider: this.provider,
      source: "current-composer",
      text,
    });
  }

  insertPrompt(text, options = {}) {
    const denied = authorized(options, "composer:write");
    if (denied) return denied;
    if (typeof text !== "string" || text.length === 0) {
      return Object.freeze({ ok: false, status: "EMPTY_PROMPT", reason: "Prompt text is required" });
    }
    const health = this.healthCheck();
    if (!health.ok) return health;
    const { composer } = this._resolve();
    if (!composer) return unavailable("Recognized composer disappeared before insertion");
    const view = composer.ownerDocument?.defaultView ?? globalThis;
    const EventCtor = view.Event ?? globalThis.Event;
    if (!EventCtor || typeof composer.dispatchEvent !== "function") {
      return unavailable("The recognized composer cannot emit an input event");
    }
    const previous = textOf(composer);
    try {
      const tag = tagOf(composer);
      const contentEditable = lower(attr(composer, "contenteditable")) === "true";
      const valueControl = !contentEditable && (tag === "textarea" || tag === "input" || "value" in composer);
      if (valueControl) {
        const prototype = tag === "textarea"
          ? view?.HTMLTextAreaElement?.prototype
          : view?.HTMLInputElement?.prototype;
        const setter = prototype ? Object.getOwnPropertyDescriptor(prototype, "value")?.set : undefined;
        if (setter) setter.call(composer, text);
        else composer.value = text;
      } else {
        composer.textContent = text;
      }
      composer.dispatchEvent(new EventCtor("input", { bubbles: true, composed: true }));
      return Object.freeze({
        ok: true,
        status: "PROMPT_INSERTED",
        provider: this.provider,
        textLength: text.length,
        // The site send control is never touched: only the composer is written.
        sendTriggered: false,
      });
    } catch {
      try {
        if (typeof previous === "string") {
          const tag = tagOf(composer);
          const contentEditable = lower(attr(composer, "contenteditable")) === "true";
          const valueControl = !contentEditable && (tag === "textarea" || tag === "input" || "value" in composer);
          if (valueControl) composer.value = previous;
          else composer.textContent = previous;
        }
      } catch {
        // Fail closed without exposing any page text in the result.
      }
      return unavailable("Prompt insertion was refused by the recognized DOM");
    }
  }

  _responseResolution() {
    const resolution = this._resolve();
    if (!resolution.assistant || !resolution.content) {
      return { ...resolution, responseMissing: true };
    }
    return { ...resolution, responseMissing: false };
  }

  observeResponse(options = {}) {
    const denied = authorized(options, "response:read");
    if (denied) return denied;
    const health = this.healthCheck();
    if (!health.ok) return health;
    const resolution = this._responseResolution();
    if (resolution.responseMissing) {
      return Object.freeze({
        ok: false,
        status: "NO_RESPONSE",
        provider: this.provider,
        reason: "No recognized current model response is available",
      });
    }
    const signal = streamingSignal(this._streamRoots(resolution));
    return Object.freeze({
      ok: true,
      status: signal ? "STREAMING" : "READY",
      provider: this.provider,
      streaming: Boolean(signal),
      streamingSignal: signal,
      stable: false,
      responseKey: this._responseKey(resolution.assistant),
    });
  }

  isResponseStreaming(options = {}) {
    const observation = this.observeResponse(options);
    if (!observation.ok) return observation;
    return Object.freeze({
      ok: true,
      status: observation.status,
      streaming: observation.streaming,
      responseKey: observation.responseKey,
    });
  }

  captureFinalResponse(options = {}) {
    const denied = authorized(options, "response:read");
    if (denied) return denied;
    const {
      stableMs = 0,
      requiredStableWindows = DEFAULT_STABLE_WINDOWS,
      now = () => Date.now(),
    } = options;
    const health = this.healthCheck();
    if (!health.ok) return health;
    const resolution = this._responseResolution();
    if (resolution.responseMissing) {
      return Object.freeze({
        ok: false,
        status: "NO_RESPONSE",
        provider: this.provider,
        reason: "No recognized current model response is available",
        certifiable: false,
      });
    }
    const responseKey = this._responseKey(resolution.assistant);
    const signal = streamingSignal(this._streamRoots(resolution));
    const text = textOf(resolution.content);
    if (typeof text !== "string" || text.length === 0) {
      this._noteStability({ key: responseKey, text: null, streaming: true, now, requiredStableMs: stableMs, requiredWindows: requiredStableWindows });
      return Object.freeze({
        ok: false,
        status: "EMPTY_RESPONSE",
        provider: this.provider,
        reason: "The recognized response is empty",
        certifiable: false,
        text: null,
        responseKey,
      });
    }
    const stability = this._noteStability({
      key: responseKey,
      text,
      streaming: Boolean(signal),
      now,
      requiredStableMs: stableMs,
      requiredWindows: requiredStableWindows,
    });
    if (signal) {
      // No partial text is ever returned on this path.
      return Object.freeze({
        ok: false,
        status: "STREAMING",
        provider: this.provider,
        reason: "The model response is still streaming",
        streamingSignal: signal,
        certifiable: false,
        text: null,
        responseKey,
      });
    }
    if (!stability.stable) {
      return Object.freeze({
        ok: true,
        status: "STABILIZING",
        provider: this.provider,
        stable: false,
        streaming: false,
        certifiable: false,
        stableWindows: stability.windows,
        requiredStableWindows,
        text: null,
        responseKey,
      });
    }
    return Object.freeze({
      ok: true,
      status: "FINAL",
      provider: this.provider,
      stable: true,
      streaming: false,
      certifiable: true,
      stableWindows: stability.windows,
      text,
      responseKey,
    });
  }

  /**
   * Wait for a non-streaming, byte-for-byte stable current response.  The
   * text is returned only after the same exact string survived the complete
   * stability window; a timeout never certifies a partial stream.
   */
  async waitForFinalResponse({
    authorized: isAuthorized = false,
    userGesture = false,
    timeoutMs = 30_000,
    stableMs = 0,
    pollMs = 100,
    requiredStableWindows = DEFAULT_STABLE_WINDOWS,
    now = () => Date.now(),
    sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms)),
  } = {}) {
    const options = { authorized: isAuthorized, userGesture, stableMs, requiredStableWindows, now };
    const denied = authorized(options, "response:read");
    if (denied) return denied;
    const started = now();
    let sawStreaming = false;
    while (now() - started <= timeoutMs) {
      const observation = this.observeResponse(options);
      if (observation.ok && observation.streaming) sawStreaming = true;
      const capture = this.captureFinalResponse(options);
      if (capture.ok && capture.stable && capture.streaming === false && capture.certifiable === true) {
        return capture;
      }
      await sleep(Math.max(1, pollMs));
    }
    return Object.freeze({
      ok: false,
      status: sawStreaming ? "STREAMING" : "NO_RESPONSE",
      provider: this.provider,
      reason: sawStreaming
        ? "The response did not become final before the timeout"
        : "No final response became available before the timeout",
      certifiable: false,
      text: null,
    });
  }

  attachProjection(projection, options = {}) {
    const denied = authorized(options, "response:read");
    if (denied) return denied;
    const health = this.healthCheck();
    if (!health.ok) return health;
    const resolution = this._responseResolution();
    if (resolution.responseMissing) {
      return unavailable("Cannot attach a projection without a recognized current response");
    }
    // The mount is the model turn's own parent, so the projection lands beside
    // the whole Gemini answer and never inside the text node that was hashed.
    const target = resolution.content;
    const mount = resolution.assistant?.parentNode ?? resolution.container?.parentNode ?? target?.parentNode;
    if (!target || !mount || typeof mount.appendChild !== "function") {
      return unavailable("The recognized response has no safe sibling projection mount");
    }

    let label;
    let hash;
    try {
      label = String(projection?.label ?? projection?.trustStatus ?? "Safi").slice(0, 200);
      hash = String(projection?.responseSha256 ?? "");
    } catch {
      return unavailable("Projection data could not be read safely");
    }
    if (!/^[0-9a-f]{64}$/i.test(hash)) {
      return unavailable("Projection hash is not a SHA-256 digest");
    }
    let trustStatus;
    try {
      trustStatus = String(projection?.trustStatus ?? "");
    } catch {
      return unavailable("Projection trust status could not be read safely");
    }
    if (!PROJECTION_TRUST_STATUSES.has(trustStatus)) {
      return unavailable("Projection trust status is not recognized");
    }

    const before = textOf(target);
    if (typeof before !== "string") {
      return unavailable("The recognized response text is unavailable for projection");
    }
    if (options.expectedResponseText !== undefined && before !== options.expectedResponseText) {
      return unavailable("The recognized response changed before projection");
    }
    let existing;
    try {
      existing = [...(mount.children ?? [])].find(
        (child) => lower(attr(child, "data-safi-companion-projection")) === this.provider,
      );
    } catch {
      return unavailable("The projection mount could not be inspected safely");
    }

    let element = existing;
    let created = false;
    try {
      if (!element) {
        const create = target.ownerDocument?.createElement?.bind(target.ownerDocument);
        if (!create) return unavailable("The response document cannot create a projection element");
        element = create("aside");
        created = true;
        mount.appendChild(element);
      }
      element.setAttribute?.("data-safi-companion-projection", this.provider);
      element.setAttribute?.("data-safi-ignore", "true");
      element.setAttribute?.("data-safi-response-sha256", hash);
      element.setAttribute?.("role", "status");
      element.setAttribute?.("aria-label", String(projection?.ariaLabel ?? `Safi: ${label}`).slice(0, 300));
      element.textContent = `${label} · ${hash.slice(0, 8)}…${hash.slice(-8)}`;
    } catch {
      if (created) {
        try {
          element?.remove?.();
        } catch {
          // Keep the original DOM failure fail-closed.
        }
      }
      return unavailable("Projection attachment was refused by the DOM");
    }
    const after = textOf(target);
    if (before !== after) {
      try {
        element.remove?.();
      } catch {
        // The response mismatch is still a hard refusal even if cleanup fails.
      }
      return unavailable("Projection attachment changed the response text; refusing the result");
    }
    return Object.freeze({
      ok: true,
      status: "PROJECTED",
      provider: this.provider,
      attached: true,
      responseUnchanged: true,
      projection: Object.freeze({
        schema: "safi-companion-projection/v0.1",
        trustStatus,
        label,
        responseSha256: hash,
        separate: true,
      }),
    });
  }
}

/** True when the bounded stop allowlist matches anywhere in the document. */
function streamSignalsPresent(doc) {
  for (const selector of STREAMING_SIGNALS.controls) {
    if (queryAll(doc, selector).length > 0) return true;
  }
  return false;
}

